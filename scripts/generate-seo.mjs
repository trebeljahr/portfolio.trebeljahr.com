import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, "..");
const siteUrl = "https://portfolio.trebeljahr.com";
const lastmod = (process.env.SITEMAP_LASTMOD || new Date().toISOString()).slice(0, 10);

const routes = [
  { path: "/", changefreq: "weekly", priority: "1.0" },
  { path: "/cv", changefreq: "monthly", priority: "0.8" },
  { path: "/imprint", changefreq: "yearly", priority: "0.2" },
];

function absoluteUrl(path) {
  return new URL(path, siteUrl).toString();
}

function sitemapXml() {
  const urls = routes
    .map(
      ({ path, changefreq, priority }) => `  <url>
    <loc>${absoluteUrl(path)}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`,
    )
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo.mjs. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

function robotsTxt() {
  return `# Generated by scripts/generate-seo.mjs. Do not edit by hand.
User-agent: *
Allow: /

Sitemap: ${absoluteUrl("/sitemap.xml")}
`;
}

await mkdir(join(rootDir, "public"), { recursive: true });
await writeFile(join(rootDir, "public", "sitemap.xml"), sitemapXml());
await writeFile(join(rootDir, "public", "robots.txt"), robotsTxt());
